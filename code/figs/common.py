def style():
    """Grayscale-safe style with 8 pt text at final size."""
    mpl.rcParams.update({
        "font.family": "DejaVu Sans",
        "font.size": 8, "axes.titlesize": 8, "axes.labelsize": 8,
        "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
        "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
        "lines.linewidth": 1.0, "lines.markersize": 4,
        "pdf.fonttype": 42, "ps.fonttype": 42,
        "savefig.bbox": "tight", "savefig.pad_inches": 0.02,
        "axes.spines.top": False, "axes.spines.right": False,
    })


def name(det):
    n = NAME.get(det)
    return None if n in EXCLUDE else n


def save(fig, stem):
    path = OUT / f"{stem}.pdf"
    # Empty metadata: no author and no local path in the embedded figure.
    fig.savefig(path, metadata={"Creator": None, "Producer": None, "Author": None,
                                "Title": None})
    print("wrote", path.relative_to(ROOT) if str(path).startswith(str(ROOT)) else path)
