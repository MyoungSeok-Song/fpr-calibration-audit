"""Shared paths, detector names and plot style for the figures.

Every figure and every derived number is computed from result tables (no number is typed by hand). By default the frozen
tables in results/ are read; set FIG_SRC=out to plot the tables regenerated by the scripts in code/.
C1 is not released, so it does not appear in the figures of this repository.
"""
import os
import pathlib

import matplotlib as mpl

ROOT = pathlib.Path(__file__).resolve().parents[2]          # repository root
TAB = ROOT / os.environ.get('FIG_SRC', 'results')   # an absolute FIG_SRC replaces ROOT
OUT = pathlib.Path(os.environ.get('OUT_DIR', str(ROOT / 'out'))) / 'figs'
OUT.mkdir(parents=True, exist_ok=True)

# Detector name in the result tables -> name printed in the figures.
